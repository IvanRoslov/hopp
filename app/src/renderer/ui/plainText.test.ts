import { describe, expect, it } from 'vitest';
import { plainLine } from './plainText';

describe('plainLine', () => {
  it.each([
    ['Этап «Дизайн» готов. Спека описывает **сетку**, типографику', 'Этап «Дизайн» готов. Спека описывает сетку, типографику'],
    ['## Итоги этапа\n\nВсё готово.', 'Итоги этапа'],
    ['- первый `pnpm`\n- второй', 'первый pnpm'],
    ['1. Пункт **один**', 'Пункт один'],
    ['См. [анализ](analysis@2) и [сайт](https://example.com)', 'См. анализ и сайт'],
    ['![схема](./chart.png) готова', 'схема готова'],
    ['***Жирный курсив*** и ~~зачёркнутое~~', 'Жирный курсив и зачёркнутое'],
    ['**Вложенная *разметка* внутри**', 'Вложенная разметка внутри'],
    ['Шаблон `**/*.ts` и `a * b`', 'Шаблон **/*.ts и a * b'],
    ['> Цитата\n> на две строки', 'Цитата'],
    ['Первая строка\nвторая строка того же абзаца', 'Первая строка'],
    ['Список  с   пробелами\tи табом', 'Список с пробелами и табом'],
    ['A &amp; B &lt; C', 'A & B < C'],
    ['\n\n   \n## \n\nТекст после пустого заголовка', 'Текст после пустого заголовка'],
    ['Plain question?', 'Plain question?'],
  ])('%j → %j', (input, want) => {
    expect(plainLine(input)).toBe(want);
  });
});
